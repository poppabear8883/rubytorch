#!/usr/bin/env node
// Contrast gate (plan §2a). Runs as `prebuild`: reads the colour tokens from
// src/index.css and exits non-zero if any text/surface pair misses its threshold.
// Usage: node scripts/contrast.mjs [--write]   (--write refreshes the comment in index.css)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const cssPath = resolve(here, '../src/index.css')
const css = readFileSync(cssPath, 'utf8')

const tokens = {}
for (const m of css.matchAll(/--color-([a-z-]+):\s*(#[0-9a-fA-F]{6})\s*;/g)) tokens[m[1]] = m[2]

const hex = (s) => [1, 3, 5].map((i) => parseInt(s.slice(i, i + 2), 16))
const lum = (s) => {
  const [r, g, b] = hex(s).map((v) => {
    v /= 255
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const ratio = (a, b) => {
  const x = lum(a)
  const y = lum(b)
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}

// [foreground, background, minimum, usage]
// Not allowed (fails): Crimson text on surface-raised (2.99:1). Ember small text off Graphite.
const pairs = [
  ['ivory', 'surface', 4.5, 'body text'],
  ['ivory', 'surface-alt', 4.5, 'body text'],
  ['ivory', 'surface-raised', 4.5, 'body text'],
  ['blush', 'surface', 4.5, 'secondary text'],
  ['blush', 'surface-alt', 4.5, 'secondary text'],
  ['blush', 'surface-raised', 4.5, 'secondary text'],
  ['ember', 'graphite', 4.5, 'small ruby text, Graphite only'],
  ['ivory', 'crimson', 4.5, 'primary button'],
  ['ivory', 'ruby', 4.5, 'button hover'],
  ['crimson', 'graphite', 3, 'large type >=24px'],
  ['crimson', 'surface-alt', 3, 'large type >=24px'],
]

// Product accent text. Accents carry small text only where listed here; everything else is marks, rules and glows.
// Worst case behind text: the product's glow stops mixed 32% into Graphite (the family-card hover and the world glows peak below that).
// Tokens are added to the table as `mix:<token>@<percent>`, derived below.
const TINT = 0.32
const mix = (a, b, t) => '#' + hex(a).map((v, i) => Math.round(v * (1 - t) + hex(b)[i] * t).toString(16).padStart(2, '0')).join('').toUpperCase()
const accents = [
  ['fx-cyan', ['fx-blue', 'fx-cyan']],
  ['cb-teal', ['cb-orange', 'cb-teal', 'cb-violet']],
  ['ph-amber', ['ph-flame', 'ph-amber']],
]
for (const [text, glows] of accents) {
  for (const g of glows) {
    if (!tokens[g] || !tokens.graphite) continue
    const name = `tint-${g}`
    tokens[name] = mix(tokens.graphite, tokens[g], TINT)
    pairs.push(['ivory', name, 4.5, `body text on ${g} glow (32% mix)`])
    pairs.push(['blush', name, 4.5, `secondary text on ${g} glow (32% mix)`])
    pairs.push([text, name, 4.5, `${text} label on ${g} glow (32% mix)`])
  }
  pairs.push([text, 'graphite', 4.5, `${text} label text`])
  pairs.push([text, 'surface-alt', 4.5, `${text} label text`])
}
// Phoenix approval ticks use ph-amber on the motif card; gate icon uses fx-cyan on surface-alt (covered above).
pairs.push(['ph-amber', 'surface-raised', 4.5, 'Phoenix motif labels on motif cards'])
// Graphics only (WCAG 1.4.11, 3:1): product accents used for icon strokes and rules on Graphite.
pairs.push(['fx-blue', 'graphite', 3, 'rule / gradient start (non-text)'])
pairs.push(['cb-violet', 'graphite', 3, 'star icon stroke (non-text)'])
pairs.push(['cb-orange', 'graphite', 3, 'dot (non-text)'])

let failed = false
const lines = []
for (const [fg, bg, min, use] of pairs) {
  if (!tokens[fg] || !tokens[bg]) {
    console.error(`contrast: missing token --color-${!tokens[fg] ? fg : bg}`)
    failed = true
    continue
  }
  const r = ratio(tokens[fg], tokens[bg])
  const ok = r >= min
  if (!ok) failed = true
  const line = `${fg.padEnd(8)} on ${bg.padEnd(15)} ${r.toFixed(2).padStart(5)}:1  (min ${min}) ${ok ? 'ok ' : 'FAIL'}  ${use}`
  lines.push(line)
  console[ok ? 'log' : 'error'](`contrast: ${line}`)
}

if (process.argv.includes('--write') && !failed) {
  const block = `/* contrast:start (generated by scripts/contrast.mjs --write)\n${lines.map((l) => '   ' + l).join('\n')}\n   contrast:end */`
  const next = css.match(/\/\* contrast:start[\s\S]*?contrast:end \*\//)
    ? css.replace(/\/\* contrast:start[\s\S]*?contrast:end \*\//, block)
    : css + '\n' + block + '\n'
  writeFileSync(cssPath, next)
}

if (failed) {
  console.error('contrast: gate FAILED. Fix the tokens in src/index.css before building.')
  process.exit(1)
}
console.log('contrast: all pairs pass')
